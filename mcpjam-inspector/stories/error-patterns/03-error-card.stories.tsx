import type { Meta, StoryObj } from "@storybook/react-vite";
import { ErrorCard } from "@/components/ui/error-card";
import { BeforeAfter, Panel, SurfaceFrame } from "./_support/layout";
import { normalizedError, useToastSpecimen } from "./_support/specimens";

/**
 * PATTERN 3 — ErrorCard.
 *
 * The surface for "a failure with a real cause and a real next step", and the
 * default for anything with a diagnosis. It is the only pattern with room for
 * all four of: what failed, why, what to do, and the raw text a support ticket
 * needs.
 *
 * These stories render the REAL component from
 * `client/src/components/ui/error-card.tsx`. An earlier draft of this
 * Storybook lived in the design system and had to show a replica, because the
 * design system cannot import app code. Moving the Storybook here is what let
 * it show the actual thing, which has 8 test files of its own.
 *
 * `useFeedbackReporter` returns null without its provider, so the card renders
 * here exactly as it does in the app minus the "send feedback" affordance.
 */
/**
 * No `component: ErrorCard` here, deliberately. Naming it would make Storybook
 * require `args` on every story, and these stories compose a whole before/after
 * surface through `render` rather than driving one card by its props. The cost
 * is the autogenerated props table; the card's props are documented in its own
 * source, and this page is about when to reach for the pattern.
 */
const meta = {
  title: "Error Patterns/3. ErrorCard",
  parameters: {
    layout: "padded",
    docs: {
      description: {
        component:
          "The richest surface, and the default for anything with a diagnosis. " +
          "Thin error copy is usually a placement problem rather than a writing " +
          "problem: the message is short because a toast had no room for the " +
          "cause or the step. This is the surface that does.",
      },
    },
  },
} satisfies Meta;

export default meta;
type Story = StoryObj<typeof meta>;

/**
 * The commonest failure in the product, and the commonest way to get it wrong:
 * pass `error.message` straight to a toast.
 */
export const ServerConnectionFailure: Story = {
  name: "A server refuses the connection",
  render: function ServerConnectionFailureStory() {
    useToastSpecimen((toast) =>
      toast.error(
        "FetchError: request to https://api.internal.acme.com/mcp failed, reason: connect ECONNREFUSED 10.0.4.12:443",
        { duration: Infinity },
      ),
    );

    return (
      <BeforeAfter>
        <Panel
          kind="before"
          caption="A raw transport error forwarded verbatim to a surface that cannot hold it. Pinned open; in the product it would be gone before it was read."
          provenance="illustrative"
broken={[
            "E1 — Raw `error.message`. Unbounded, unreviewed, and in this shape it can carry a URL with a token in the query string.",
            "E2 — Names a socket, not the server. The reader does not know which of their servers this is about.",
            "E3 — Nothing to do. No retry, no setting, no sentence.",
            "Placement — The cause and the next step would not fit in a toast even if someone wrote them.",
          ]}
        >
          <SurfaceFrame title="Servers">
            <p className="text-sm text-muted-foreground">
              The toast bottom-right is the whole of what the reader gets.
            </p>
          </SurfaceFrame>
        </Panel>

        <Panel
          kind="after"
          caption="The same failure through the real ErrorCard, with the diagnosis the catalog already holds."
          broken={[
            "E1 — The transport string moved into the collapsed detail, redacted and copyable. The message is sentences.",
            "E2 — Names the server, and states the cause once.",
            "E3 — Retry (this one genuinely might succeed) plus the steps no button can take.",
            "Placement — ErrorCard, because there is a real cause and a real next step.",
          ]}
        >
          <SurfaceFrame title="Servers">
            <ErrorCard
              error={normalizedError({
                title: "Couldn't connect to Acme Internal",
                oneLine: "The server refused the connection.",
                likelyCauses: [
                  "Nothing is listening at api.internal.acme.com on port 443.",
                ],
                nextSteps: [
                  "Check the server is running and reachable from this network.",
                  "If it moved, update the URL in the server's settings.",
                ],
                rawMessage:
                  "FetchError: request to https://api.internal.acme.com/mcp failed, reason: connect ECONNREFUSED 10.0.4.12:443",
              })}
              onRetry={() => undefined}
            />
          </SurfaceFrame>
        </Panel>
      </BeforeAfter>
    );
  },
};

/**
 * Why the real card separates `action` from `onRetry`: retrying a failure that
 * cannot change just fails again. The example is the sign-in case from the
 * conformance page, where the code says the same thing in a comment ("A plain
 * retry would hit the same missing sign-in, so this one opens it").
 *
 * Both panels are the real ErrorCard in its bordered layout. The only change
 * is the button. `density="card"` is what keeps the border: left unset, an
 * `action` switches the card to a compact one-line row made for server cards.
 */
export const RetryWouldNotHelp: Story = {
  name: "Retry is the wrong affordance",
  render: () => (
    <BeforeAfter>
      <Panel
        kind="before"
        caption="The real ErrorCard with a Retry button, on a failure that retrying cannot fix."
        provenance="composite"
        broken={[
          "E3 — Retry is in reach but useless: the sign-in is still missing, so it fails the same way again.",
          "Composite: the title and sentence are the ones the conformance page shows today; putting them in an ErrorCard with Retry is ours.",
        ]}
      >
        <SurfaceFrame title="Servers">
          <ErrorCard
            error={normalizedError({
              title: 'Couldn\'t connect to "Linear"',
              oneLine: "It needs you to sign in again.",
            })}
            onRetry={() => undefined}
          />
        </SurfaceFrame>
      </Panel>

      <Panel
        kind="after"
        caption="The same card. The button is now the thing that fixes it."
        broken={[
          "E3 — Every ErrorCard offers a way out: Retry when trying again can work, otherwise the specific action.",
        ]}
      >
        <SurfaceFrame title="Servers">
          <ErrorCard
            error={normalizedError({
              title: 'Couldn\'t connect to "Linear"',
              oneLine: "It needs you to sign in again.",
            })}
            density="card"
            action={{ label: "Sign in", onClick: () => undefined }}
          />
        </SurfaceFrame>
      </Panel>
    </BeforeAfter>
  ),
};

