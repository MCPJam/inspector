// Bundle the codex app-server bridge into a generated TS module.
//
// Two entrypoints, because Codex runs one of them itself:
//   bridge.mjs          - the bridge the host spawns
//   host-tools-mcp.mjs  - the MCP server Codex spawns, which calls back into it
//
// WHY A GENERATED TS CONST rather than shipping the .mjs as a file: nothing in
// the server's import graph references these entrypoints (they are uploaded
// into a sandbox and executed there), so the bundler never walks to them and
// the published package would not contain them. Same reason, same shape, as
// `bundle-plugin-shim.mjs` and `bundle-browser-harness.mjs`.
//
// The emitted version is the content hash of everything in the bundle, and it
// feeds the bootstrap identity — so editing the bridge forks existing sessions
// instead of resuming them onto a box running the old code.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const __dirname = dirname(fileURLToPath(import.meta.url));
const adapterDir = join(
  __dirname,
  "../server/utils/harness/codex-appserver",
);
const outputPath = join(
  adapterDir,
  "bootstrap/generated/codex-appserver-bridge.bundled.ts",
);

/**
 * Kept EXTERNAL because the bootstrap installs them in the sandbox.
 *
 * THE BUNDLING TRIPLE. Every entry here must appear in three places or the
 * bridge dies inside the box with a module-not-found nobody can see:
 *
 *   1. the import in the bridge source,
 *   2. this array,
 *   3. `bootstrap/package.json`'s dependencies.
 *
 * `ws` is reached transitively — the bridge imports `@ai-sdk/harness/bridge`,
 * which esbuild inlines, and the inlined code imports `ws` for its WebSocket
 * server. It is a PEER dependency of the harness package, so nothing installs
 * it on our behalf; the bootstrap manifest pins it at the version the published
 * codex adapter pins.
 *
 * `bundle-codex-appserver-bridge.test.ts` asserts (2) and (3) agree with what
 * the built bundle actually imports, so adding a dependency and forgetting the
 * manifest fails a unit test rather than a turn.
 */
export const CODEX_APPSERVER_BRIDGE_EXTERNALS = ["ws"];
const EXTERNAL = CODEX_APPSERVER_BRIDGE_EXTERNALS;

async function bundleEntry(relativeEntry) {
  const result = await build({
    entryPoints: [join(adapterDir, relativeEntry)],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    write: false,
    external: EXTERNAL,
    // The bridge runs inside a disposable sandbox and its stack traces are the
    // only debugging surface there, so keep it readable.
    minify: false,
    banner: {
      js: "// Generated by scripts/bundle-codex-appserver-bridge.mjs — do not edit.",
    },
  });
  const output = result.outputFiles?.[0];
  if (!output) throw new Error(`esbuild produced no output for ${relativeEntry}`);
  return output.text;
}

export async function bundleCodexAppServerBridge() {
  // Both entrypoints guard their module-level start on an env flag so importing
  // the source in a unit test cannot bind a socket or spawn a process. The
  // shipped artifacts are the ones that actually run, so the call is appended
  // here instead.
  const bridgeSource = `${await bundleEntry("bridge/index.ts")}\nmain();\n`;
  // The MCP entrypoint's module-level autostart is env-gated so importing it
  // in a test does not hijack the runner's stdin; Codex runs it with the flag.
  const hostToolsSource = `${await bundleEntry(
    "bridge/host-tools-mcp.ts",
  )}\nstartHostToolMcpServer();\n`;
  const packageJson = readFileSync(
    join(adapterDir, "bootstrap/package.json"),
    "utf8",
  );

  const version = createHash("sha256")
    .update(bridgeSource, "utf8")
    .update(hostToolsSource, "utf8")
    .update(packageJson, "utf8")
    .digest("hex")
    .slice(0, 32);

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(
    outputPath,
    `// This file is auto-generated by scripts/bundle-codex-appserver-bridge.mjs
// Do not edit directly — modify server/utils/harness/codex-appserver/bridge/** instead.

export const CODEX_APPSERVER_BRIDGE_SOURCE = ${JSON.stringify(bridgeSource)};

export const CODEX_APPSERVER_HOST_TOOLS_MCP_SOURCE = ${JSON.stringify(
      hostToolsSource,
    )};

export const CODEX_APPSERVER_BOOTSTRAP_PACKAGE_JSON = ${JSON.stringify(
      packageJson,
    )};

/** sha256 over everything above, truncated. Feeds the bootstrap identity. */
export const CODEX_APPSERVER_BUNDLE_VERSION = ${JSON.stringify(version)};
`,
  );

  return { bridgeSource, hostToolsSource, packageJson, version, outputPath };
}

// Run as a script (the `bundle:*` npm task); importable as a module (the test).
if (process.argv[1] && process.argv[1].endsWith("bundle-codex-appserver-bridge.mjs")) {
  try {
    const { bridgeSource, hostToolsSource, version } =
      await bundleCodexAppServerBridge();
    process.stdout.write(
      `Bundled codex app-server bridge (${(bridgeSource.length / 1024).toFixed(
        1,
      )} KiB) + host-tools MCP (${(hostToolsSource.length / 1024).toFixed(
        1,
      )} KiB), version ${version}\n`,
    );
  } catch (error) {
    process.stderr.write(
      `Failed to bundle codex app-server bridge: ${
        error instanceof Error ? error.stack : String(error)
      }\n`,
    );
    process.exit(1);
  }
}
