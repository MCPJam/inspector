// Bundle the LOCAL Inspector layer into a generated TS module.
//
// The layer is the half of a local harness runtime that is MCPJam's own code:
// the loopback/resolution launcher and each harness's bridge (Codex also has
// the host-tools MCP entrypoint Codex spawns). It ships with the Inspector —
// as string constants compiled into the server, the same shape and reason as
// `bundle-codex-appserver-bridge.mjs` — and `inspector-layer.ts` writes it to a
// content-addressed, read-only directory at run time. A bridge change is
// therefore an ordinary Inspector change: no runtime pack is rebuilt for it.
//
// What is NOT here: anything a vendor pack carries. The bridge bundles inline
// every dependency of their own (`ws`, the MCP SDK, `zod`); the only module a
// layer may import at run time is a vendor SDK resolved from the verified pack
// (`layer/launcher.mjs` enforces that).
//
// Output is gitignored (`*.bundled.ts`) and rebuilt by `build`, `bundle:all`
// and `pretest`, like the other generated bundles.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import {
  bundleCodexAppServerLayerSources,
  LAYER_REQUIRE_BANNER,
  stubOptionalNatives,
} from "./bundle-codex-appserver-bridge.mjs";
import { vendorSdkVersion } from "./local-harness-pack-recipes/claude-code.mjs";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const inspectorRoot = join(scriptDir, "..");
const layerDir = join(inspectorRoot, "server/utils/harness/local/layer");
export const LOCAL_HARNESS_LAYER_OUTPUT = join(
  layerDir,
  "generated/local-harness-layer.bundled.ts",
);

/**
 * The ONE module the Claude Code bridge leaves external: the agent SDK, which
 * shares a version with its native binary and so stays in the vendor pack. The
 * layer's launcher resolves it to the pack at run time (`--mcpjam-vendor-root`).
 */
export const CLAUDE_CODE_LAYER_BRIDGE_EXTERNALS = ["@anthropic-ai/claude-agent-sdk"];

const load = (path) =>
  import("tsx/esm/api").then(({ tsImport }) =>
    tsImport(path, { parentURL: import.meta.url, tsconfig: false }),
  );

/**
 * The Claude Code bridge for the layer: the adapter's bridge exactly as the
 * application patches it (`claude-code-bootstrap.ts`), bundled with the MCP
 * SDK, `zod` and `ws` compiled in. Those resolve as this repository resolves
 * them, like the Codex bridge's dependencies — the agent SDK is self-contained
 * and only ever sees the bridge's MCP server through `connect(transport)`, so
 * the bridge's copies never cross into it.
 *
 * Refuses an adapter whose recipe expects a different agent SDK than the
 * vendor pack pins: that bridge would import an SDK the pack does not carry.
 * Re-pin `scripts/local-harness-pack-recipes/claude-code-vendor/` (a new pack).
 */
async function bundleClaudeCodeLayerBridge() {
  const { createClaudeCodeHarness } = await load("../server/utils/harness/claude-code-bootstrap.ts");
  const recipe = await createClaudeCodeHarness().getBootstrap();
  const bridge = recipe.files.find((file) => file.path === `${recipe.bootstrapDir}/bridge.mjs`);
  const manifest = recipe.files.find((file) => file.path === `${recipe.bootstrapDir}/package.json`);
  if (!bridge || !manifest) throw new Error("the Claude Code recipe has no bridge.mjs or package.json");
  const adapterSdk = JSON.parse(manifest.content).dependencies?.["@anthropic-ai/claude-agent-sdk"];
  if (adapterSdk !== vendorSdkVersion()) {
    throw new Error(
      `the Claude Code adapter's bridge expects @anthropic-ai/claude-agent-sdk ` +
        `${adapterSdk}, but the vendor pack pins ${vendorSdkVersion()}. Update ` +
        `scripts/local-harness-pack-recipes/claude-code-vendor/ (package.json, then ` +
        `pnpm install --lockfile-only) — merging that publishes a new Claude Code pack.`,
    );
  }
  const result = await build({
    stdin: {
      contents: bridge.content,
      // Resolved from the Inspector package, the way the server resolves its
      // own dependencies, and named in esbuild's module comments relative to
      // it — pinned, so the bytes do not depend on who bundles from where.
      resolveDir: inspectorRoot,
      sourcefile: "claude-code-bridge.mjs",
      loader: "js",
    },
    absWorkingDir: inspectorRoot,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    write: false,
    external: CLAUDE_CODE_LAYER_BRIDGE_EXTERNALS,
    plugins: [stubOptionalNatives],
    minify: false,
    banner: {
      js: `// Generated by scripts/bundle-local-harness-layer.mjs — do not edit.\n${LAYER_REQUIRE_BANNER}`,
    },
  });
  const output = result.outputFiles?.[0];
  if (!output) throw new Error("esbuild produced no Claude Code bridge");
  return {
    bridgeSource: output.text,
    recipe: { harnessId: recipe.harnessId, bootstrapDir: recipe.bootstrapDir, commands: recipe.commands },
  };
}

/**
 * The ONE module the Copilot CLI bridge leaves external: the SDK, which drives
 * the CLI it is released with and so stays in the vendor pack. The launcher
 * resolves it there (`--mcpjam-vendor-root`); `ws` and the harness bridge kit
 * are compiled in, like the Codex bridge's.
 */
export const COPILOT_LAYER_BRIDGE_EXTERNALS = ["@github/copilot-sdk"];

/** The Copilot CLI bridge for the layer, and the recipe a local session keeps. */
async function bundleCopilotLayerBridge() {
  const result = await build({
    entryPoints: [join(inspectorRoot, "server/utils/harness/copilot-cli/bridge/index.ts")],
    absWorkingDir: inspectorRoot,
    preserveSymlinks: true,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    write: false,
    external: COPILOT_LAYER_BRIDGE_EXTERNALS,
    plugins: [stubOptionalNatives],
    minify: false,
    banner: {
      js: `// Generated by scripts/bundle-local-harness-layer.mjs — do not edit.\n${LAYER_REQUIRE_BANNER}`,
    },
  });
  const output = result.outputFiles?.[0];
  if (!output) throw new Error("esbuild produced no Copilot CLI bridge");
  const { COPILOT_BOOTSTRAP_COMMANDS, COPILOT_BOOTSTRAP_DIR } = await load(
    "../server/utils/harness/copilot-cli/bootstrap-recipe.ts",
  );
  return {
    files: { "bridge.mjs": output.text },
    recipe: {
      harnessId: "copilot-cli",
      bootstrapDir: COPILOT_BOOTSTRAP_DIR,
      commands: COPILOT_BOOTSTRAP_COMMANDS.map((command) => ({ command })),
    },
  };
}

/**
 * Cursor's ACP bridge and its host-tool MCP entrypoint for the layer: the
 * hosted bridge as the application patches it, with the local launch change
 * (`cursor-local-bridge.ts`), and every dependency compiled in. Nothing is
 * left external: the pack is Cursor's own package, and the bridge drives the
 * CLI over stdio.
 */
async function bundleCursorLayerBridge() {
  const { localCursorBootstrapRecipe } = await load("../server/utils/harness/cursor-local-bridge.ts");
  const recipe = await localCursorBootstrapRecipe();
  const files = {};
  for (const name of ["bridge.mjs", "host-tool-mcp.mjs"]) {
    const file = recipe.files.find((entry) => entry.path === `${recipe.bootstrapDir}/${name}`);
    if (!file) throw new Error(`the Cursor recipe has no ${name}`);
    const result = await build({
      stdin: { contents: file.content, resolveDir: inspectorRoot, sourcefile: `cursor-${name}`, loader: "js" },
      absWorkingDir: inspectorRoot,
      bundle: true,
      platform: "node",
      format: "esm",
      target: "node22",
      write: false,
      plugins: [stubOptionalNatives],
      minify: false,
      banner: {
        js: `// Generated by scripts/bundle-local-harness-layer.mjs — do not edit.\n${LAYER_REQUIRE_BANNER}`,
      },
    });
    const output = result.outputFiles?.[0];
    if (!output) throw new Error(`esbuild produced no Cursor ${name}`);
    files[name] = output.text;
  }
  return {
    files,
    recipe: { harnessId: recipe.harnessId, bootstrapDir: recipe.bootstrapDir, commands: recipe.commands },
  };
}

/** The Codex recipe's directory and commands, which a local session keeps. */
async function codexRecipeMeta() {
  const { getCodexAppServerBootstrap } = await load(
    "../server/utils/harness/codex-appserver/codex-appserver-bootstrap.ts",
  );
  const recipe = getCodexAppServerBootstrap();
  return { harnessId: recipe.harnessId, bootstrapDir: recipe.bootstrapDir, commands: recipe.commands };
}

/**
 * How each local runtime's layer is built: its files (besides the launcher and
 * `layer.json`, which every layer has) and the recipe directory and commands
 * its adapter declares. One entry per runtime in
 * `server/utils/harness/local/runtimes/`; `local-runtimes.test.ts` checks the
 * two lists agree and that each runtime's `layerFiles` are what is built here.
 */
const LAYER_BUILDERS = {
  "claude-code": async () => {
    const claude = await bundleClaudeCodeLayerBridge();
    return { files: { "bridge.mjs": claude.bridgeSource }, recipe: claude.recipe };
  },
  codex: async () => {
    const codex = await bundleCodexAppServerLayerSources();
    return {
      files: { "bridge.mjs": codex.bridgeSource, "host-tools-mcp.mjs": codex.hostToolsSource },
      recipe: await codexRecipeMeta(),
    };
  },
  "copilot-cli": bundleCopilotLayerBridge,
  cursor: bundleCursorLayerBridge,
};

/** Every layer source, without writing anything. */
export async function bundleLocalHarnessLayerSources() {
  const launcherSource = readFileSync(join(layerDir, "launcher.mjs"), "utf8");
  const files = {};
  const recipes = {};
  for (const [harnessId, build] of Object.entries(LAYER_BUILDERS)) {
    const layer = await build();
    files[harnessId] = layer.files;
    recipes[harnessId] = layer.recipe;
  }
  return { launcherSource, files, recipes };
}

export async function bundleLocalHarnessLayer() {
  const sources = await bundleLocalHarnessLayerSources();
  mkdirSync(dirname(LOCAL_HARNESS_LAYER_OUTPUT), { recursive: true });
  writeFileSync(
    LOCAL_HARNESS_LAYER_OUTPUT,
    `// This file is auto-generated by scripts/bundle-local-harness-layer.mjs
// Do not edit directly — modify server/utils/harness/local/layer/launcher.mjs
// or the bridge sources instead.

/** \`layer/launcher.mjs\`, verbatim. */
export const LOCAL_HARNESS_LAUNCHER_SOURCE = ${JSON.stringify(sources.launcherSource)};

/**
 * Each local runtime's layer files besides the launcher and \`layer.json\`,
 * every dependency of their own inlined: file name to contents.
 */
export const LOCAL_HARNESS_LAYER_FILES: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(sources.files)};

/**
 * Each runtime's recipe directory and commands, as the adapter declares them.
 * A local session's recipe is these plus the layer's files — built from
 * constants, so Electron never has to read an adapter package from disk.
 */
export const LOCAL_HARNESS_LAYER_RECIPES: Readonly<
  Record<string, { harnessId: string; bootstrapDir: string; commands: Array<{ command: string }> }>
> = ${JSON.stringify(sources.recipes)};
`,
  );
  return sources;
}

if (process.argv[1] && process.argv[1].endsWith("bundle-local-harness-layer.mjs")) {
  try {
    const sources = await bundleLocalHarnessLayer();
    const sizes = Object.entries(sources.files).map(
      ([harnessId, files]) =>
        `${harnessId} ${(Object.values(files).reduce((total, text) => total + text.length, 0) / 1024).toFixed(1)} KiB`,
    );
    process.stdout.write(
      `Bundled local harness layer: launcher ${(sources.launcherSource.length / 1024).toFixed(1)} KiB, ${sizes.join(", ")}\n`,
    );
  } catch (error) {
    process.stderr.write(
      `Failed to bundle the local harness layer: ${
        error instanceof Error ? error.stack : String(error)
      }\n`,
    );
    process.exit(1);
  }
}
