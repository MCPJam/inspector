// Bundle the LOCAL Inspector layer into a generated TS module.
//
// The layer is the half of a local harness runtime that is MCPJam's own code:
// the loopback/resolution launcher and each harness's bridge (Codex also has
// the host-tools MCP entrypoint Codex spawns). It ships with the Inspector —
// as string constants compiled into the server, the same shape and reason as
// `bundle-codex-appserver-bridge.mjs` — and `inspector-layer.ts` writes it to a
// content-addressed, read-only directory at run time. A bridge change is
// therefore an ordinary Inspector change: no runtime pack is rebuilt for it.
//
// What is NOT here: anything a vendor pack carries. The bridge bundles inline
// every dependency of their own (`ws`, the MCP SDK, `zod`); the only module a
// layer may import at run time is a vendor SDK resolved from the verified pack
// (`layer/launcher.mjs` enforces that).
//
// Output is gitignored (`*.bundled.ts`) and rebuilt by `build`, `bundle:all`
// and `pretest`, like the other generated bundles.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { bundleCodexAppServerLayerSources } from "./bundle-codex-appserver-bridge.mjs";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const inspectorRoot = join(scriptDir, "..");
const layerDir = join(inspectorRoot, "server/utils/harness/local/layer");
export const LOCAL_HARNESS_LAYER_OUTPUT = join(
  layerDir,
  "generated/local-harness-layer.bundled.ts",
);

/** Every layer source, without writing anything. */
export async function bundleLocalHarnessLayerSources() {
  const launcherSource = readFileSync(join(layerDir, "launcher.mjs"), "utf8");
  const codex = await bundleCodexAppServerLayerSources();
  return {
    launcherSource,
    codexBridgeSource: codex.bridgeSource,
    codexHostToolsSource: codex.hostToolsSource,
  };
}

export async function bundleLocalHarnessLayer() {
  const sources = await bundleLocalHarnessLayerSources();
  mkdirSync(dirname(LOCAL_HARNESS_LAYER_OUTPUT), { recursive: true });
  writeFileSync(
    LOCAL_HARNESS_LAYER_OUTPUT,
    `// This file is auto-generated by scripts/bundle-local-harness-layer.mjs
// Do not edit directly — modify server/utils/harness/local/layer/launcher.mjs
// or the bridge sources instead.

/** \`layer/launcher.mjs\`, verbatim. */
export const LOCAL_HARNESS_LAUNCHER_SOURCE = ${JSON.stringify(sources.launcherSource)};

/** The Codex app-server bridge, with every dependency inlined. */
export const CODEX_LAYER_BRIDGE_SOURCE = ${JSON.stringify(sources.codexBridgeSource)};

/** The host-tools MCP entrypoint Codex spawns, layer variant. */
export const CODEX_LAYER_HOST_TOOLS_MCP_SOURCE = ${JSON.stringify(sources.codexHostToolsSource)};
`,
  );
  return sources;
}

if (process.argv[1] && process.argv[1].endsWith("bundle-local-harness-layer.mjs")) {
  try {
    const sources = await bundleLocalHarnessLayer();
    process.stdout.write(
      `Bundled local harness layer: launcher ${(sources.launcherSource.length / 1024).toFixed(1)} KiB, ` +
        `codex bridge ${(sources.codexBridgeSource.length / 1024).toFixed(1)} KiB\n`,
    );
  } catch (error) {
    process.stderr.write(
      `Failed to bundle the local harness layer: ${
        error instanceof Error ? error.stack : String(error)
      }\n`,
    );
    process.exit(1);
  }
}
