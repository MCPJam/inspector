// Bundles the mcpjam-browserd daemon (server/services/browserd/daemon/main.ts)
// into a single self-contained ESM file the boot recipe copies into the desktop
// sandbox and runs with `node`. Unlike the plugin-shim bundler, the output is
// CHECKED IN (server/services/browserd/dist/mcpjam-browserd.mjs), so the sandbox
// needs no build step — regenerate with `npm run bundle:browserd` after touching
// the daemon and commit the result.
//
// `playwright` is left EXTERNAL: it (and its Chromium binaries) are installed in
// the desktop template, not shipped in this artifact. The daemon reaches it via
// the dynamic `import("playwright")` in chromium-launch.ts.
import { build } from "esbuild";
import { fileURLToPath } from "url";
import { dirname, resolve } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const entry = resolve(root, "server/services/browserd/daemon/main.ts");
const outfile = resolve(
  root,
  "server/services/browserd/dist/mcpjam-browserd.mjs",
);

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  external: ["playwright", "playwright-core"],
  legalComments: "none",
  banner: {
    js: "#!/usr/bin/env node\n// AUTO-GENERATED by scripts/bundle-browserd.mjs — do not edit by hand.",
  },
});

console.log(`bundled browserd → ${outfile}`);
