/**
 * The v2 run verdict AGGREGATOR, and the adapter that turns one iteration's
 * evidence into the trial observation it consumes.
 *
 * This module is browser-safe and intentionally has no node-only deps.
 *
 * `./verdict-policy.ts` is the contract — shapes, vocabularies, validators —
 * and deliberately ships no aggregator. The backend has had one all along
 * (`convex/lib/evalVerdictPolicy.ts#aggregateEvalRunVerdict`), called by both
 * hosted and SDK-ingest finalization. A LOCAL producer — `runSuiteFile`, which
 * decides a run with no backend involved — needs the same arithmetic, and this
 * is it: a hand mirror of the backend's pure dependency closure, not a
 * re-derivation. The messages a refusal carries are the backend's too, so a
 * malformed input is refused for the same reason on both sides.
 *
 * ── How the two stay one policy ─────────────────────────────────────────────
 *
 * Two implementations of one policy drift silently while each keeps passing
 * its own tests, so both are held to shared, generated ground truth:
 *
 *   - `tests/fixtures/eval-verdict-policy-parity-fixtures.json` pins the
 *     per-case roll-up (its `aggregation` cohort), and
 *   - `tests/fixtures/eval-verdict-run-aggregation-parity-fixtures.json`,
 *     OWNED and generated by mcpjam-backend from its aggregator, pins whole
 *     runs — full expected decisions — plus the finalization adapter's reading
 *     of iteration evidence.
 *
 * Both are byte-for-byte copies; neither is edited here. A change to the
 * arithmetic is a change to BOTH repos in step, regenerated on the backend.
 *
 * ── What is ported, and what is not ─────────────────────────────────────────
 *
 * Ported: the input checks the aggregator runs (policy, identity and caps,
 * configured trials, thresholds, lifecycle statuses), the arithmetic, the
 * reason derivation and order, and the finalization adapter
 * (`evalV2IterationHasEvaluatorError`, `evalV2TrialObservation`).
 *
 * The backend's hand-written decision validator is NOT ported: the SDK already
 * has one, `evalVerdictDecisionSchema`, proven equivalent by the per-case
 * corpus. Every decision this module returns is parsed by it first — a
 * producer must never emit what its own contract refuses to read back. Only
 * the two identity rules of that validator a producer can trip from its INPUT
 * (a `caseId` outside the opaque-id charset, a malformed execution variant) are
 * checked explicitly, with the backend's messages, ahead of that parse.
 */

