/**
 * Malformed v2 evidence or policy, refused rather than aggregated.
 *
 * A caller turns this into an `inconclusive` run with an integrity reason —
 * never into a legacy fallback, which would restate v2 evidence under v1
 * semantics and call it a result.
 */
export class EvalVerdictAggregationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "EvalVerdictAggregationError";
  }
}

function fail(message: string): never {
  throw new EvalVerdictAggregationError(
    `Invalid eval verdict policy payload: ${message}`
  );
}

function failFinalization(message: string): never {
  throw new EvalVerdictAggregationError(`eval verdict v2: ${message}`);
}

// ── input checks (mirror convex/lib/evalVerdictPolicy.ts) ────────────────────

const POLICY_FIELDS = [
  "coverage",
  "minCompletionRate",
  "maxEvaluatorErrorRate",
] as const;
const COVERAGE_DEFAULT_FIELDS = ["kind", "minGradeableTrials"] as const;
const COVERAGE_EXPLICIT_FIELDS = ["kind", "minEligibleTrials"] as const;
const EXECUTION_VARIANT_FIELDS = ["model", "provider"] as const;

/** What an omitted `minEligibleTrials` pins the gradeable floor to. */
const DEFAULT_MIN_GRADEABLE_TRIALS = 1;

const OPAQUE_ID_PATTERN = /^[A-Za-z0-9_-]{1,128}$/;

function assertObject(value: unknown, label: string): Record<string, unknown> {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    fail(`${label} must be an object`);
  }
  return value as Record<string, unknown>;
}

function assertClosed(
  value: Record<string, unknown>,
  allowed: readonly string[],
  label: string
): void {
  for (const key of Object.keys(value)) {
    if (!allowed.includes(key)) {
      fail(
        `${label} has unknown field "${key}" (allowed: ${allowed.join(", ")})`
      );
    }
  }
}

/** A count of trials: a non-negative integer. */
function assertTrialCount(value: unknown, label: string): number {
  if (typeof value !== "number" || !Number.isInteger(value) || value < 0) {
    fail(`${label} must be a non-negative integer`);
  }
  return value;
}

/** A rate or a threshold: a finite real in [0,1]. NEVER a percent. */
function assertFraction(value: unknown, label: string): number {
  if (typeof value !== "number" || !Number.isFinite(value)) {
    fail(`${label} must be a finite number`);
  }
  if (value < 0 || value > 1) {
    fail(
      `${label} must be a fraction in [0,1] — v2 thresholds are fractions, ` +
        `never percentages (received ${value})`
    );
  }
  return value;
}

function assertValidResolvedEvalValidityPolicy(
  value: unknown,
  label = "validity policy"
): void {
  const policy = assertObject(value, label);
  assertClosed(policy, POLICY_FIELDS, label);
  assertFraction(policy.minCompletionRate, `${label}.minCompletionRate`);
  assertFraction(
    policy.maxEvaluatorErrorRate,
    `${label}.maxEvaluatorErrorRate`
  );

  const coverage = assertObject(policy.coverage, `${label}.coverage`);
  if (coverage.kind === "allConfiguredTrialsAttempted") {
    assertClosed(coverage, COVERAGE_DEFAULT_FIELDS, `${label}.coverage`);
    if (coverage.minGradeableTrials !== DEFAULT_MIN_GRADEABLE_TRIALS) {
      fail(
        `${label}.coverage.minGradeableTrials is pinned to ` +
          `${DEFAULT_MIN_GRADEABLE_TRIALS} under the default coverage rule`
      );
    }
    return;
  }
  if (coverage.kind !== "minEligibleTrials") {
    fail(
      `${label}.coverage.kind must be "allConfiguredTrialsAttempted" or ` +
        `"minEligibleTrials"`
    );
  }
  assertClosed(coverage, COVERAGE_EXPLICIT_FIELDS, `${label}.coverage`);
  const minEligible = assertTrialCount(
    coverage.minEligibleTrials,
    `${label}.coverage.minEligibleTrials`
  );
  if (minEligible < 1) {
    fail(`${label}.coverage.minEligibleTrials must be at least 1`);
  }
}

function assertValidExecutionVariant(value: unknown, label: string): void {
  const variant = assertObject(value, label);
  assertClosed(variant, EXECUTION_VARIANT_FIELDS, label);
  for (const field of ["model", "provider"] as const) {
    const entry = variant[field];
    if (field === "provider" && entry === undefined) continue;
    if (typeof entry !== "string" || entry.length === 0) {
      fail(`${label}.${field} must be a non-empty string`);
    }
    if (entry.length > MAX_SUITE_FILE_TITLE_CHARS) {
      fail(
        `${label}.${field} must be at most ${MAX_SUITE_FILE_TITLE_CHARS} characters`
      );
    }
  }
}

/**
 * The identity and cap rules for a set of case aggregates — checked on the
 * INPUTS, so the failure names what the caller sent.
 *
 * All four rules stop one silent collapse each: a duplicate (caseId, variant)
 * key would double a denominator; a case carrying both a variant-keyed and an
 * unkeyed aggregate would treat omission as a wildcard (it means "this run did
 * not fan out"); and the two caps bound what one decision can summarize.
 */
function assertDistinctCaseAggregationIdentities(
  entries: ReadonlyArray<{
    caseId: string;
    executionVariant?: EvalExecutionVariant;
  }>,
  label = "cases"
): void {
  if (entries.length > MAX_EVAL_CASE_AGGREGATIONS) {
    fail(
      `${entries.length} ${label} aggregations exceeds the maximum of ` +
        `${MAX_EVAL_CASE_AGGREGATIONS}`
    );
  }
  const seenKeys = new Set<string>();
  const variantedCases = new Set<string>();
  const unvariantedCases = new Set<string>();
  for (const entry of entries) {
    const key = evalCaseAggregationKey(entry);
    if (seenKeys.has(key)) {
      fail(
        `case "${entry.caseId}" already has an aggregate for this execution ` +
          `variant; a fan-out run reports ONE row per provider/model pair`
      );
    }
    seenKeys.add(key);
    (entry.executionVariant ? variantedCases : unvariantedCases).add(
      entry.caseId
    );
  }
  for (const caseId of variantedCases) {
    if (unvariantedCases.has(caseId)) {
      fail(
        `case "${caseId}" mixes variant-keyed and unkeyed aggregates: an ` +
          `omitted executionVariant means "this run did not fan out", not ` +
          `"any variant", so the two cannot describe the same case`
      );
    }
  }
  const distinctCases = new Set(entries.map((entry) => entry.caseId)).size;
  if (distinctCases > MAX_SUITE_FILE_CASES) {
    fail(
      `${distinctCases} distinct cases exceeds the portable suite-file ` +
        `maximum of ${MAX_SUITE_FILE_CASES}`
    );
  }
}

/**
 * The two rules of the decision validator a producer can trip from its input,
 * with the backend validator's own messages — see the module docblock.
 */
function assertProducibleCaseIdentity(
  entry: EvalCaseVerdictAggregation,
  label: string
): void {
  if (
    typeof entry.caseId !== "string" ||
    !OPAQUE_ID_PATTERN.test(entry.caseId)
  ) {
    fail(`${label}.caseId must match ${OPAQUE_ID_PATTERN.source}`);
  }
  if (entry.executionVariant !== undefined) {
    assertValidExecutionVariant(
      entry.executionVariant,
      `${label}.executionVariant`
    );
  }
}

// ── the aggregator ───────────────────────────────────────────────────────────

/**
 * One trial as the producer observed it.
 *
 * `status` is the LIFECYCLE (`ITERATION_STATUSES`), `taskVerdict` the graded
 * outcome, and `evaluatorError` says the GRADER broke. All three are supplied
 * explicitly: deriving a task verdict from a lifecycle status is the
 * "we never ran it" → "it passed" collapse this vocabulary exists to prevent,
 * and nothing here reads a legacy `passed` boolean.
 */
export type EvalTrialObservation = {
  status: IterationStatus;
  taskVerdict?: "passed" | "failed";
  evaluatorError?: boolean;
};

/** One (case, execution variant)'s configured population and its trials. */
export type EvalCaseVerdictInput = {
  caseId: string;
  executionVariant?: EvalExecutionVariant;
  configuredTrials: number;
  effectivePassThreshold: number;
  trials: readonly EvalTrialObservation[];
};

/**
 * Statuses that mean the trial never BEGAN, or was withdrawn.
 *
 * A `running` trial has begun, so it stays in the attempted denominator and
 * its unfinished state lowers the completion rate. A `cancelled` one is
 * withdrawn from EVERY denominator: the harness took its outcome away.
 */
const NOT_ATTEMPTED_STATUSES: readonly IterationStatus[] = [
  "pending",
  "skipped",
  "cancelled",
];

/** Which exclusion reason a non-gradeable trial is recorded under. */
function exclusionReasonFor(
  trial: EvalTrialObservation
): EvalTrialExclusionReason {
  switch (trial.status) {
    case "pending":
    case "running":
      return "notTerminal";
    case "skipped":
      return "skipped";
    case "setup_failed":
      return "setupFailed";
    case "cancelled":
      return "cancelled";
    case "timed_out":
      return "timedOut";
    case "failed":
      return "executionFailed";
    case "completed":
      if (trial.evaluatorError) return "evaluatorError";
      // falls through to the malformed-evidence refusal below
      break;
    default:
      // Exhaustive at COMPILE time; this is the runtime edge — evidence from
      // a newer producer, or a status since retired. An unlabelled trial in a
      // tally would make the arithmetic disagree with its own counts.
      fail(
        `trial carries unknown lifecycle status ` +
          `${JSON.stringify(trial.status)}; v2 evidence must use the mirrored ` +
          `iteration-status vocabulary`
      );
  }
  // A completed trial with neither a task verdict nor an evaluator error is
  // MALFORMED evidence, not an outcome: guessing a reason is how a grader
  // failure becomes a server failure, or the reverse.
  fail(
    `trial for a completed iteration carries neither a task verdict nor an ` +
      `evaluator error; v2 evidence must say which`
  );
}

function tallyExclusion(
  tally: EvalTrialExclusions,
  reason: EvalTrialExclusionReason
): void {
  tally[reason] = (tally[reason] ?? 0) + 1;
}

function measure(
  numerator: number,
  denominator: number,
  exclusions: EvalTrialExclusions
): EvalRateMeasurement {
  if (denominator === 0) {
    return {
      state: "notMeasured",
      value: null,
      numerator: 0,
      denominator: 0,
      exclusions,
    };
  }
  return {
    state: "measured",
    value: numerator / denominator,
    numerator,
    denominator,
    exclusions,
  };
}

/** The per-case counts the suite-level validity phase needs. */
type CaseTally = {
  aggregation: EvalCaseVerdictAggregation;
  completedTrials: number;
  evaluatorErrorTrials: number;
  attemptExclusions: EvalTrialExclusions;
};

function aggregateCase(input: EvalCaseVerdictInput): CaseTally {
  if (
    !Number.isInteger(input.configuredTrials) ||
    input.configuredTrials < 1 ||
    input.configuredTrials > MAX_REPETITIONS
  ) {
    fail(
      `configuredTrials for case "${input.caseId}" must be an integer within ` +
        `1..${MAX_REPETITIONS} (per execution variant)`
    );
  }
  assertFraction(
    input.effectivePassThreshold,
    `case "${input.caseId}" effectivePassThreshold`
  );

  let attempted = 0;
  let eligible = 0;
  let passed = 0;
  let failedTrials = 0;
  let completed = 0;
  let evaluatorErrors = 0;
  // Exclusions travel PER RATE: the trials removed from an eligibility
  // denominator are not the ones removed from a completion denominator.
  const eligibilityExclusions: EvalTrialExclusions = {};
  const attemptExclusions: EvalTrialExclusions = {};

  for (const trial of input.trials) {
    const isAttempted = !NOT_ATTEMPTED_STATUSES.includes(trial.status);
    if (isAttempted) attempted += 1;
    if (trial.status === "completed") completed += 1;
    if (trial.status === "completed" && trial.evaluatorError) {
      evaluatorErrors += 1;
    }

    const gradeable =
      trial.status === "completed" &&
      !trial.evaluatorError &&
      trial.taskVerdict !== undefined;
    if (gradeable) {
      eligible += 1;
      if (trial.taskVerdict === "passed") passed += 1;
      else failedTrials += 1;
      continue;
    }

    const reason = exclusionReasonFor(trial);
    tallyExclusion(eligibilityExclusions, reason);
    if (!isAttempted) tallyExclusion(attemptExclusions, reason);
  }

  if (input.trials.length > input.configuredTrials) {
    fail(
      `case "${input.caseId}" reported ${input.trials.length} trials for ` +
        `${input.configuredTrials} configured`
    );
  }
  // Configured-but-unreported trials never began: the same thing a `pending`
  // row says, recorded the same way, so a producer that omits stubs and one
  // that writes them produce identical decisions.
  const unreported = input.configuredTrials - input.trials.length;
  if (unreported > 0) {
    eligibilityExclusions.notTerminal =
      (eligibilityExclusions.notTerminal ?? 0) + unreported;
    attemptExclusions.notTerminal =
      (attemptExclusions.notTerminal ?? 0) + unreported;
  }

  const passRate = measure(passed, eligible, eligibilityExclusions);
  const completionRate = measure(completed, attempted, attemptExclusions);
  const observedStability = measure(
    Math.max(passed, failedTrials),
    eligible,
    eligibilityExclusions
  );

  const verdict: EvalRunVerdict =
    eligible === 0
      ? "inconclusive"
      : passRate.value !== null &&
          passRate.value >= input.effectivePassThreshold
        ? "passed"
        : "failed";
  const reason: EvalVerdictDecisionReason =
    eligible === 0
      ? "caseHasNoEligibleTrials"
      : verdict === "passed"
        ? "casePassRateMetThreshold"
        : "casePassRateBelowThreshold";

  return {
    aggregation: {
      caseId: input.caseId,
      ...(input.executionVariant
        ? { executionVariant: input.executionVariant }
        : {}),
      configuredTrials: input.configuredTrials,
      attemptedTrials: attempted,
      eligibleTrials: eligible,
      passedTrials: passed,
      failedTrials,
      effectivePassThreshold: input.effectivePassThreshold,
      passRate,
      completionRate,
      observedStability,
      mixedVerdict: passed > 0 && failedTrials > 0,
      verdict,
      reason,
    },
    completedTrials: completed,
    evaluatorErrorTrials: evaluatorErrors,
    attemptExclusions,
  };
}

/** Roll ONE case's trials up — the per-case corpus's `aggregation` cohort. */
export function aggregateEvalCaseVerdict(
  input: EvalCaseVerdictInput
): EvalCaseVerdictAggregation {
  return aggregateCase(input).aggregation;
}

function mergeExclusions(
  into: EvalTrialExclusions,
  from: EvalTrialExclusions
): void {
  for (const reason of EVAL_TRIAL_EXCLUSION_REASONS) {
    const count = from[reason];
    if (count === undefined) continue;
    into[reason] = (into[reason] ?? 0) + count;
  }
}

/**
 * The reasons a failed validity phase produces: the FAILED checks, all of them
 * and only them.
 */
function expectedValidityReasons(
  validity: EvalVerdictValidity,
  completionMet: boolean,
  evaluatorMet: boolean,
  everyCaseMeasured: boolean
): EvalValidityDecisionReason[] {
  const reasons: EvalValidityDecisionReason[] = [];
  if (validity.policy.coverage.kind === "allConfiguredTrialsAttempted") {
    if (validity.attemptedTrials !== validity.configuredTrials) {
      reasons.push("configuredTrialsNotAttempted");
    }
    if (validity.eligibleTrials < validity.policy.coverage.minGradeableTrials) {
      reasons.push("noGradeableTrials");
    }
  } else if (
    validity.eligibleTrials < validity.policy.coverage.minEligibleTrials
  ) {
    reasons.push("eligibleTrialsBelowMinimum");
  }
  if (validity.completionRate.state !== "measured") {
    reasons.push("completionRateNotMeasured");
  } else if (!completionMet) {
    reasons.push("completionRateBelowMinimum");
  }
  if (validity.evaluatorErrorRate.state !== "measured") {
    reasons.push("evaluatorErrorRateNotMeasured");
  } else if (!evaluatorMet) {
    reasons.push("evaluatorErrorRateAboveMaximum");
  }
  if (!everyCaseMeasured) reasons.push("caseHasNoEligibleTrials");
  return reasons;
}

function taskVerdictFromCases(
  cases: readonly EvalCaseVerdictAggregation[]
): EvalRunVerdict {
  if (cases.some((entry) => entry.verdict === "inconclusive")) {
    return "inconclusive";
  }
  if (cases.some((entry) => entry.verdict === "failed")) return "failed";
  return "passed";
}

/**
 * Parse the produced decision with the SDK's own contract validator before
 * returning it: a producer must never emit what its contract refuses to read
 * back. A refusal here is a bug in this module, never in the caller's input —
 * every input rule is checked above with its own message.
 */
function selfChecked(decision: EvalVerdictDecision): EvalVerdictDecision {
  decision.cases.forEach((entry, index) =>
    assertProducibleCaseIdentity(entry, `cases[${index}]`)
  );
  const parsed = evalVerdictDecisionSchema.safeParse(decision);
  if (!parsed.success) {
    fail(
      `the produced decision violates the verdict contract: ${parsed.error.issues
        .map((issue) => `${issue.path.join(".")}: ${issue.message}`)
        .join("; ")}`
    );
  }
  return decision;
}

/**
 * THE v2 decision — the same function, rule for rule, that hosted and SDK
 * ingest finalization call on the backend.
 *
 * Pure: no clock, no I/O. Throws {@link EvalVerdictAggregationError} on
 * malformed evidence or policy (a completed trial with no verdict and no
 * evaluator error, a threshold outside [0,1], more trials than configured, a
 * duplicate identity), which a caller turns into an `inconclusive` run with an
 * integrity reason rather than a fallback.
 */
export function aggregateEvalRunVerdict(args: {
  policy: ResolvedEvalValidityPolicy;
  cases: readonly EvalCaseVerdictInput[];
}): EvalVerdictDecision {
  assertValidResolvedEvalValidityPolicy(args.policy);
  if (args.cases.length === 0) {
    fail("a v2 decision needs at least one case aggregate");
  }
  // Identity and caps BEFORE any arithmetic, on the INPUTS, so the failure
  // names what the caller sent rather than a decision already built.
  assertDistinctCaseAggregationIdentities(args.cases);

  const tallies = args.cases.map(aggregateCase);
  const cases = tallies.map((tally) => tally.aggregation);

  let configured = 0;
  let attempted = 0;
  let eligible = 0;
  let completed = 0;
  let evaluatorErrors = 0;
  const attemptExclusions: EvalTrialExclusions = {};
  for (const tally of tallies) {
    configured += tally.aggregation.configuredTrials;
    attempted += tally.aggregation.attemptedTrials;
    eligible += tally.aggregation.eligibleTrials;
    completed += tally.completedTrials;
    evaluatorErrors += tally.evaluatorErrorTrials;
    mergeExclusions(attemptExclusions, tally.attemptExclusions);
  }

  const completionRate = measure(completed, attempted, attemptExclusions);
  const evaluatorErrorRate = measure(
    evaluatorErrors,
    attempted,
    attemptExclusions
  );

  const coverageMet =
    args.policy.coverage.kind === "minEligibleTrials"
      ? eligible >= args.policy.coverage.minEligibleTrials
      : attempted === configured &&
        eligible >= args.policy.coverage.minGradeableTrials;
  const completionMet =
    completionRate.state === "measured" &&
    completionRate.value >= args.policy.minCompletionRate;
  const evaluatorMet =
    evaluatorErrorRate.state === "measured" &&
    evaluatorErrorRate.value <= args.policy.maxEvaluatorErrorRate;
  const everyCaseMeasured = cases.every((entry) => entry.eligibleTrials > 0);
  const holds =
    coverageMet && completionMet && evaluatorMet && everyCaseMeasured;

  const validity: EvalVerdictValidity = {
    policy: args.policy,
    holds,
    configuredTrials: configured,
    attemptedTrials: attempted,
    eligibleTrials: eligible,
    completionRate,
    evaluatorErrorRate,
  };

  if (!holds) {
    const reasons = expectedValidityReasons(
      validity,
      completionMet,
      evaluatorMet,
      everyCaseMeasured
    ).sort(
      (left, right) =>
        EVAL_VERDICT_DECISION_REASONS.indexOf(left) -
        EVAL_VERDICT_DECISION_REASONS.indexOf(right)
    );
    return selfChecked({
      verdictPolicyVersion: EVAL_VERDICT_POLICY_VERSION,
      verdict: "inconclusive",
      reasons,
      validity,
      cases,
    });
  }

  const verdict = taskVerdictFromCases(cases);
  return selfChecked({
    verdictPolicyVersion: EVAL_VERDICT_POLICY_VERSION,
    verdict,
    reasons: [
      verdict === "passed"
        ? "allMeasuredCasesMetThreshold"
        : "casePassRateBelowThreshold",
    ],
    validity,
    cases,
  });
}

